"""Render, rewrite and check the README's Commands block from the command table.

Run `python -m agent_tools.readme_commands` to rewrite the block between the
markers, or with `--check` to exit 1 on the first line that differs. The core
below is pure; `main` is the only code that reads or writes README.md.
"""

from __future__ import annotations

import argparse
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

BEGIN = "<!-- commands:begin (generated by `python -m devtools commands render`; do not edit) -->"
END = "<!-- commands:end -->"
FIX = "run `python -m agent_tools.readme_commands` with no flag to rewrite the block, then commit README.md"

_NO_VALUE = ("store_true", "store_false", "count")


def _metavar(arg: Any) -> str:
    """The value placeholder: an explicit metavar, else choices as a|b|c, else the upper-cased name."""
    kw = arg.kwargs
    if "metavar" in kw:
        return str(kw["metavar"])
    if "choices" in kw:
        return "|".join(str(c) for c in kw["choices"])
    name = kw.get("dest") or next((f for f in arg.flags if f.startswith("--")), arg.flags[0])
    return name.lstrip("-").replace("-", "_").upper()


def _arg_text(arg: Any) -> str:
    kw = arg.kwargs
    if not arg.flags[0].startswith("-"):
        nargs = kw.get("nargs")
        meta = _metavar(arg)
        return {"?": f"[{meta}]", "*": f"[{meta}...]"}.get(nargs, meta)
    text = arg.flags[0] if kw.get("action") in _NO_VALUE else f"{arg.flags[0]} {_metavar(arg)}"
    return text if kw.get("required") else f"[{text}]"


def _line(path: str, args: Sequence[Any], help_text: str) -> str:
    return "   ".join([" ".join(["cox", path, *(_arg_text(a) for a in args)]), help_text])


def _row_lines(path: str, row: Any) -> list[str]:
    """A row with subcommands lists only its children, even when it has a handler of its own
    (`setup store`): the README block has never carried such a parent line."""
    own = [] if row.subcommands else [_line(f"{path} {row.name}", row.args, row.summary)]
    return own + [ln for child in row.subcommands for ln in _row_lines(f"{path} {row.name}", child)]


def _group_lines(group: Any, rows: Sequence[Any]) -> list[str]:
    return [ln for row in rows for ln in _row_lines(group.name, row)] if rows else [_line(group.name, group.args, group.help)]


def render_block(table: Sequence[tuple[Any, Sequence[Any]]]) -> str:
    """The fenced block, one line per command in table order. A group with no rows is one leaf line."""
    lines = [ln for group, rows in table for ln in _group_lines(group, rows)]
    return "\n".join(["```", *lines, "```"]) + "\n"


def splice(readme: str, block: str) -> str | None:
    """README text with only the span between the markers replaced; None when a marker is missing."""
    head, sep, rest = readme.partition(BEGIN + "\n")
    _, end_sep, tail = rest.partition(END)
    return None if not sep or not end_sep else head + sep + block + END + tail


def block_of(readme: str) -> str | None:
    """The text between the markers, or None when a marker is missing."""
    _, sep, rest = readme.partition(BEGIN + "\n")
    body, end_sep, _ = rest.partition(END)
    return body if sep and end_sep else None


def first_diff(expected: str, actual: str) -> tuple[int, str, str] | None:
    """(1-based line number, expected line, actual line) at the first difference, or None when equal."""
    if expected == actual:
        return None
    want, got = expected.split("\n"), actual.split("\n")
    n = next((i for i in range(max(len(want), len(got))) if want[i : i + 1] != got[i : i + 1]), 0)
    return n + 1, "".join(want[n : n + 1]), "".join(got[n : n + 1])


def main(argv: Sequence[str] | None = None) -> int:
    from agent_tools import cli

    parser = argparse.ArgumentParser(prog="python -m agent_tools.readme_commands", description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 and print the first differing line")
    parser.add_argument("--readme", type=Path, default=Path(__file__).resolve().parent.parent / "README.md")
    opts = parser.parse_args(sys.argv[1:] if argv is None else argv)
    path = opts.readme
    readme = path.read_text(encoding="utf-8")
    block = render_block(cli.COMMAND_TABLE)
    if opts.check:
        current = block_of(readme)
        if current is None:
            print(f"{path.name}: commands markers not found")
            return 2
        diff = first_diff(block, current)
        if diff is None:
            return 0
        n, want, got = diff
        print(f"{path.name} Commands block differs at line {n}:\n  rendered: {want}\n  README:   {got}\nfix: {FIX}")
        return 1
    new = splice(readme, block)
    if new is None:
        print(f"{path.name}: commands markers not found")
        return 2
    path.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
